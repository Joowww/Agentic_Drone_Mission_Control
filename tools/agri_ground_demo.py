DEMO_SEQUENCE_ID = str(uuid.uuid5(uuid.NAMESPACE_URL, "tfg/agri-demo-001/synthetic-r1-demo"))
DEMO_FRAME = "SYNTHETIC_DEMO_FRAME"
DEMO_MISSION = {"path": "SYNTHETIC/no-mission-file", "sha256": hashlib.sha256(b"synthetic rover_01 mission").hexdigest()}
DEMO_SESSION = str(uuid.uuid5(uuid.NAMESPACE_URL, "tfg/agri-demo-001/synthetic-session"))
DEMO_LIMITS = {"rover_limits": {"max_forward_mps": .4, "max_yaw_rate_rad_s": 1., "max_duration_s": 130.,
                                "call_timeout_s": 1., "stop_timeout_s": 3., "observation_max_age_s": .5,
                                "stopped_linear_mps": .03, "stopped_angular_rad_s": .03},
               "controller": {"yaw_rad": 0., "yaw_tolerance_rad": 3.141592653589793, "command_hz": 10.,
                              "max_samples": 256, "progress_rad": .01}}


def demo_inputs(*, transform=True) -> dict:
    inputs = {
        "target_in_rover_frame": {"x_m": 0.0, "y_m": 0.0, "frame": DEMO_FRAME},
        "ground_tolerance_m": summary.R1_VISIT_PROPOSAL["arrival_tolerance_m"],
        "rover_mission": DEMO_MISSION,
        "completion_evidence": "synthetic odometry samples generated by the TEST_DOUBLE executor",
        "execution_limits": DEMO_LIMITS,
    }
    if transform:
        inputs["frame_transform"] = {"status": "VERIFIED", "sha256": hashlib.sha256(b"synthetic transform").hexdigest(),
                                     "from_frame": "SYNTHETIC_POI_FRAME", "to_frame": DEMO_FRAME}
    return {name: {"value": value, "source": "TEST_DOUBLE demo"} for name, value in inputs.items()}


def demo_authorization(prepared: dict) -> dict:
    return {"source": "OPERATOR_DECLARED", "statement": "TEST_DOUBLE declaration for the synthetic demo only",
            "candidate_sha256": prepared["candidate_sha256"], "mission_sha256": DEMO_MISSION["sha256"],
            "session_id": DEMO_SESSION}


class TestDoubleGroundExecutor:
    """Stands in for the rover's executor contract. Holds its own jobs and reservations; the coordinator has no
    way to release them (the interface has no release). No ROS, process, socket or file."""
    kind = "TEST_DOUBLE"

    def __init__(self, *, admit_mode="ADMIT", ground="ARRIVE_DWELL_STOP", lookup_supported=True):
        self.admit_mode, self.ground, self.lookup_supported = admit_mode, ground, lookup_supported
        self.policy_enabled = True
        self.jobs, self.reservations, self.admit_calls = {}, set(), 0

    def facts(self) -> dict:
        return {"kind": self.kind, "policy_enabled": self.policy_enabled, "navigation_request_supported": True,
                "navigation_request_detail": "TEST_DOUBLE ROVER_NAVIGATE_V1"}

    def admit(self, task: dict) -> dict:
        self.admit_calls += 1
        if self.admit_mode == "BLOCK":
            return {"status": "BLOCKED", "reason": "TEST_DOUBLE executor refusal"}
        key = task["request_key"]
        if key not in self.jobs:  # executor-side idempotency by request key, like the real one
            run_id = str(uuid.uuid5(uuid.NAMESPACE_URL, "tfg/test-double/" + key))
            session = task["coordination_context"]["authorization"]["session_id"]
            self.jobs[key] = {"run_id": run_id, "session_id": session, "task": task, "queries": 0}
            self.reservations.add(run_id)
        job = self.jobs[key]
        if self.admit_mode == "LOSE_RESPONSE":
            raise TimeoutError("TEST_DOUBLE: admission reply lost after the job was created")
        return {"status": "ADMITTED", "run_id": job["run_id"], "session_id": job["session_id"]}

    def lookup(self, request_key: str):
        if not self.lookup_supported:
            return None
        job = self.jobs.get(request_key)
        return {"found": True, "run_id": job["run_id"], "session_id": job["session_id"]} if job else {"found": False}

    def query(self, run_id: str) -> dict:
        job = next((j for j in self.jobs.values() if j["run_id"] == run_id), None)
        if job is None:
            return {"status": "NOT_FOUND"}
        job["queries"] += 1
        if job["queries"] == 1:
            return {"status": "RUNNING"}
        return {"status": "FINISHED", "report": {"status": "PASSED", "r1_ground_result": self._result(job)}}

    def _result(self, job: dict) -> dict:
        """Samples generated from the candidate's target: approach at 0.5 m per 0.5 s, then a stationary dwell."""
        task = job["task"]
        target = task["coordination_context"]["candidate"]["target_in_rover_frame"]["value"]
        dwell = {"ARRIVE_DWELL_STOP": 13, "SHORT_DWELL": 5, "STOP_UNCERTAIN": 13}[self.ground]
        approach = [(target["x_m"] - 10.0 + 0.5 * i, target["y_m"], 0.5) for i in range(17)]
        points = approach + [(target["x_m"] + 0.3, target["y_m"] + 0.2, 0.0)] * dwell
        samples = [{"received_monotonic_s": 100.0 + 0.5 * i, "source_stamp_ns": 50_000_000_000 + 500_000_000 * i,
                    "frame": target["frame"], "x_m": x, "y_m": y, "linear_mps": v, "angular_rad_s": 0.0}
                   for i, (x, y, v) in enumerate(points)]
        return {"schema": summary.GROUND_RESULT_SCHEMA, "task_id": "R1", "origin": "SYNTHETIC_FIXTURE",
                "binding": {"candidate_sha256": task["candidate_sha256"], "mission_sha256": task["mission_sha256"],
                            "authorization_sha256": task["authorization_sha256"], "vehicle_id": "rover_01",
                            "simulated_vehicle": "v3", "session_id": job["session_id"], "ground_run_id": job["run_id"]},
                "job_status": "PASSED", "commands": {"attempted": True, "sent": True, "started_monotonic_s": 99.0},
                "frame": {"name": target["frame"], "transform_status": "VERIFIED"}, "samples": samples,
                "decision_monotonic_s": samples[-1]["received_monotonic_s"] + 0.2,
                "stop": {"status": "UNCONFIRMED" if self.ground == "STOP_UNCERTAIN" else "STATIONARY_OBSERVED"}}


def synthetic_views(sequence: dict, binding: dict) -> dict:
    """Aerial views built by the REAL scenario_view code from a re-identified copy of a sequence record."""
    base = copy.deepcopy(sequence)
    base["sequence_id"] = DEMO_SEQUENCE_ID
    record = {"path": None, "sha256": "SYNTHETIC_DEMO"}
    failed = copy.deepcopy(base)
    summary._synthetic_failed_first(failed)
    views = {"base": summary.scenario_view(base, binding, binding_record=record),
             "first_drone_failed": summary.scenario_view(failed, binding, binding_record=record)}
    poi = copy.deepcopy(views["base"])  # VIEW-LEVEL synthetic variant: POI_A1 not reached
    poi["scenario"]["points"]["POI_A1"]["status"] = "NOT_REACHED"
    poi["scenario"]["ground_task"]["dependency"] = "NOT_MET"
    views["poi_not_reached"] = poi
    return views


VARIANTS = (  # name, view, inputs(transform), authorized, executor options
    ("complete", "base", True, True, {}),
    ("first_drone_failed", "first_drone_failed", True, True, {}),
    ("poi_not_reached", "poi_not_reached", True, True, {}),
    ("transform_absent", "base", False, True, {}),
    ("authorization_absent", "base", True, False, {}),
    ("executor_refuses", "base", True, True, {"admit_mode": "BLOCK"}),
    ("insufficient_dwell", "base", True, True, {"ground": "SHORT_DWELL"}),
    ("stop_uncertain", "base", True, True, {"ground": "STOP_UNCERTAIN"}),
    ("lost_admission_response", "base", True, True, {"admit_mode": "LOSE_RESPONSE"}),
)


def run_variant(root: Path, views: dict, name: str, view_name: str, transform: bool, authorized: bool,
                options: dict) -> dict:
    executor = TestDoubleGroundExecutor(**options)
    view, key = views[view_name], f"synthetic-r1-{name}"
    inputs = demo_inputs(transform=transform)
    prepared = coordinator.prepare(view, inputs, executor)
    authorization = demo_authorization(prepared) if authorized and prepared["candidate"] else None
    first = coordinator.request(root, key, view, inputs, authorization, executor)
    repeated = coordinator.request(root, key, view, inputs, authorization, executor)  # never a second job
    if options.get("admit_mode") == "LOSE_RESPONSE":
        executor.admit_mode = "ADMIT"  # the executor recovered; the coordinator still must not re-admit
    states = []
    for _ in range(4):  # a fresh call each time = a restarted coordinator reading only the record
        record = coordinator.track(root, key, executor)
        states.append(record.get("state"))
        if record.get("state") in coordinator.TERMINAL or record.get("state") == "NOT_FOUND":
            break
    final = coordinator.query(root, key)
    return {"variant": name, "aerial_view": view_name, "preparation": prepared["stages"],
            "request_status": first.get("request_status"), "request_reason": first.get("reason"),
            "repeat_request_status": repeated.get("request_status"), "admit_calls": executor.admit_calls,
            "tracked_states": states, "final_state": final.get("state"),
            "acceptance": (final.get("acceptance") or {}).get("outcome"),
            "acceptance_reasons": (final.get("acceptance") or {}).get("reasons"),
            "executor_reservations_held": sorted(executor.reservations),
            "scenario": coordinator.scenario_result(view, final if final.get("state") != "NOT_FOUND" else None)}


def run_demo(root: Path, sequence: dict, binding: dict) -> dict:
    views = synthetic_views(sequence, binding)
    return {"label": "OFFLINE SYNTHETIC DEMO: real coordinator, TEST_DOUBLE executor, no rover moved",
            "sequence_id": DEMO_SEQUENCE_ID,
            "variants": [run_variant(root, views, *variant) for variant in VARIANTS]}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True, help="NEW directory for the demo's own records")
    args = parser.parse_args(argv)
    args.out.mkdir(parents=True, exist_ok=False)
    path = summary.PROJECT_ROOT / summary.SCENARIOS[summary.SCENARIO_ID]["binding_record"]
    binding = summary._bind_expected(*summary.record_associations(path))
    sequence = summary.get_preflight_sequence(request_key=summary.H2_REQUEST_KEY, detail=True)  # read-only
    if sequence.get("job_state") != "FINISHED":
        print(json.dumps({"status": "NOT_READY", "reason": f"H2 sequence {sequence.get('job_state')}"}))
        return 3
    result = run_demo(args.out, sequence, binding)
    print(json.dumps(result, indent=2, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
